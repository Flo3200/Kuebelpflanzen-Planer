def seed_species(db: Session) -> None:
    if db.scalar(select(Species.id).where(Species.tenant_id.is_(None)).limit(1)) is not None:
        return
    for (
        name,
        botanical,
        aliases,
        shape,
        density,
        comp,
        kg_l,
        trunk,
        tip,
        frost,
        tilt,
        sensitive,
        height,
    ) in CATALOG:
        db.add(
            Species(
                tenant_id=None,
                name=name,
                botanical_name=botanical,
                aliases=aliases,
                crown_shape=shape,
                crown_density=density,
                compressibility=comp,
                soil_kg_per_l=1.3,
                plant_kg_per_l=kg_l,
                trunk_kg_per_m=trunk,
                tip_tendency=tip,
                frost_sensitivity=frost,
                can_tilt=tilt,
                sensitive=sensitive,
                typical_height_cm=height,
            )
        )
    db.flush()
